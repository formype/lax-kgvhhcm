const OPTION_LABELS = ['A', 'B', 'C', 'D'];

function shuffleArray(items) {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Shuffles the question bank, picks 20 questions, and shuffles A/B/C/D options per question.
 */
export function generateShuffledQuiz(count = 20) {
  const selectedQuestions = shuffleArray(SURVEY_QUESTION_BANK).slice(0, count);
  return selectedQuestions.map((q) => {
    const shuffledOptions = shuffleArray(q.options).map((opt, idx) => ({
      ...opt,
      displayLabel: OPTION_LABELS[idx]
    }));
    return {
      id: q.id,
      question: q.question,
      options: shuffledOptions
    };
  });
}
